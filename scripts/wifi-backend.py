#!/usr/bin/env python3
"""Configure SteamOS Wi-Fi without depending on Steam's current session settings."""

import argparse
import configparser
import fcntl
import json
import os
from pathlib import Path
import stat
import subprocess
import tempfile


ROOT = Path(__file__).resolve().parents[1]
BACKENDS = ("iwd", "wpa_supplicant")
VALVE_CONFIG = Path("/etc/NetworkManager/conf.d/99-valve-wifi-backend.conf")
LOCK_CONFIG = Path("/etc/NetworkManager/conf.d/zz-bc250-wifi-backend.conf")
SERVICE_CONFIG = Path("/etc/systemd/system/NetworkManager.service.d/90-bc250-wifi-backend.conf")
KEEP_FILE = Path("/etc/atomic-update.conf.d/bc250-wifi.conf")
SWITCH_HELPER = Path("/usr/bin/steamos-polkit-helpers/steamos-wifi-set-backend-privileged")
LOCK_HEADER = "# Managed by bc250-wifi-backend.sh.\n"
KEEP_HEADER = (
    "# Toolkit state preserved by SteamOS atomic updates.\n"
    "# Generated by bc250-update-persistence.sh.\n"
)


class WifiError(RuntimeError):
    pass


def run(*args, check=True):
    return subprocess.run(args, check=check, capture_output=True, text=True, timeout=90)


def regular_file(path):
    if path.is_symlink() or (path.exists() and not path.is_file()):
        raise WifiError(f"Refusing to modify non-regular file: {path}")


def read_file(path):
    regular_file(path)
    return path.read_text(encoding="utf-8") if path.exists() else None


def lock_text(backend):
    return f"{LOCK_HEADER}[device]\nwifi.backend={backend}\n"


def service_text(backend):
    # Wants (not Requires) starts the selected backend on NM activation without
    # forcing NM down if Steam stops that backend during a switch. Starting iwd
    # first also lets it recreate interfaces destroyed when its service stopped.
    return f"{LOCK_HEADER}[Unit]\nWants={backend}.service\nAfter={backend}.service\n"


def service_binding():
    text = read_file(SERVICE_CONFIG)
    if text is None:
        return None
    for backend in BACKENDS:
        if text == service_text(backend):
            return backend
    raise WifiError(f"Unrecognized Wi-Fi service binding: {SERVICE_CONFIG}")


def locked_backend():
    text = read_file(LOCK_CONFIG)
    if text is None:
        return None
    for backend in BACKENDS:
        if text == lock_text(backend):
            return backend
    raise WifiError(f"Unrecognized Wi-Fi lock configuration: {LOCK_CONFIG}")


def effective_backend():
    result = run("NetworkManager", "--print-config")
    parser = configparser.ConfigParser(interpolation=None, strict=False)
    parser.read_string(result.stdout)
    # NetworkManager defaults to wpa_supplicant when no backend is configured.
    backend = parser.get("device", "wifi.backend", fallback="wpa_supplicant").strip()
    if backend not in BACKENDS:
        raise WifiError(f"Unsupported effective Wi-Fi backend: {backend}")
    return backend


def update_backend(text, backend):
    """Update only the global [device] backend, retaining unrelated settings/comments."""
    text = text or ""
    parser = configparser.ConfigParser(interpolation=None)
    parser.read_string(text)
    lines = text.splitlines(keepends=True)
    in_device = False
    found_section = False
    inserted = False
    output = []
    for line in lines:
        stripped = line.strip()
        if stripped.startswith("[") and stripped.endswith("]"):
            if in_device and not inserted:
                output.append(f"wifi.backend={backend}\n")
                inserted = True
            in_device = stripped == "[device]"
            found_section |= in_device
        if in_device and stripped.split("=", 1)[0].strip() == "wifi.backend":
            output.append(f"wifi.backend={backend}\n")
            inserted = True
        else:
            output.append(line if line.endswith("\n") else line + "\n")
    if in_device and not inserted:
        output.append(f"wifi.backend={backend}\n")
    if not found_section:
        output.append(f"[device]\nwifi.backend={backend}\n")
    return "".join(output)


def atomic_write(path, text, mode=None):
    regular_file(path)
    if mode is None:
        mode = stat.S_IMODE(path.stat().st_mode) if path.exists() else 0o644
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, name = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            stream.write(text)
            stream.flush()
            os.fsync(stream.fileno())
            os.fchmod(stream.fileno(), mode)
        os.replace(name, path)
    finally:
        if os.path.exists(name):
            os.unlink(name)


def persist(action):
    result = run("bash", str(ROOT / "bc250-update-persistence.sh"), action, "wifi")
    if result.stdout:
        print(result.stdout, end="")


def service_active(backend):
    return run("systemctl", "is-active", "--quiet", f"{backend}.service", check=False).returncode == 0


def show_status(as_json=False):
    lock = locked_backend()
    binding = service_binding()
    effective = effective_backend()
    protected = False
    if KEEP_FILE.is_file() and not KEEP_FILE.is_symlink():
        text = KEEP_FILE.read_text(encoding="utf-8")
        protected = text.startswith(KEEP_HEADER) and all(
            str(path) in text.splitlines() for path in (LOCK_CONFIG, SERVICE_CONFIG)
        )
    status = {
        "backend": effective,
        "locked_backend": lock,
        "lock_effective": lock is not None and effective == lock,
        "service_binding": binding,
        "update_protected": protected,
        "active_services": [backend for backend in BACKENDS if service_active(backend)],
    }
    if as_json:
        print(json.dumps(status))
        return
    print(f"[bc250-wifi] Effective backend: {effective}")
    print(f"[bc250-wifi] Backend lock: {lock or 'unlocked (Steam may change the backend)'}")
    if lock:
        print(f"[bc250-wifi] Lock effective: {'yes' if status['lock_effective'] else 'NO — conflicting NetworkManager configuration'}")
        print(f"[bc250-wifi] SteamOS update protection: {'installed' if protected else 'missing'}")
        print(f"[bc250-wifi] Backend startup binding: {binding or 'missing; rerun lock to repair'}")
    print(f"[bc250-wifi] Active Wi-Fi services: {', '.join(status['active_services']) or 'none'}")
    result = run("nmcli", "-f", "DEVICE,TYPE,STATE,CONNECTION", "device", "status", check=False)
    if result.stdout:
        print(result.stdout, end="")


def configure(action, backend=None):
    if os.geteuid() != 0:
        raise WifiError("Run changes with sudo, or use bc250-wifi-backend.sh.")
    lock = locked_backend()
    binding = service_binding()
    if action == "unlock" and lock is None and binding is None:
        # Also remove a keeper left behind by an interrupted unlock.
        persist("remove")
        print("[bc250-wifi] Backend is already unlocked.")
        return
    if action == "unlock":
        backend = lock or binding
    if backend not in BACKENDS:
        raise WifiError(f"Unsupported Wi-Fi backend: {backend}")
    load_state = run("systemctl", "show", "--property=LoadState", "--value", f"{backend}.service").stdout.strip()
    if load_state != "loaded":
        raise WifiError(f"Wi-Fi backend service is not available: {backend} ({load_state})")
    if not SWITCH_HELPER.is_file():
        raise WifiError(f"SteamOS Wi-Fi switch helper is missing: {SWITCH_HELPER}")
    before = effective_backend()
    original = {
        path: read_file(path)
        for path in (VALVE_CONFIG, LOCK_CONFIG, SERVICE_CONFIG, KEEP_FILE)
    }
    if original[KEEP_FILE] is not None and not original[KEEP_FILE].startswith(KEEP_HEADER):
        raise WifiError(f"Unrecognized Wi-Fi update keep list: {KEEP_FILE}")
    modes = {path: stat.S_IMODE(path.stat().st_mode) for path, text in original.items() if text is not None}
    keep_lock = action == "lock" or (action == "set" and (lock is not None or binding is not None))
    try:
        atomic_write(VALVE_CONFIG, update_backend(original[VALVE_CONFIG], backend))
        if keep_lock:
            atomic_write(LOCK_CONFIG, lock_text(backend))
            atomic_write(SERVICE_CONFIG, service_text(backend))
            persist("install")
        elif action == "unlock":
            LOCK_CONFIG.unlink(missing_ok=True)
            SERVICE_CONFIG.unlink(missing_ok=True)
            persist("remove")
        if effective_backend() != backend:
            raise WifiError("Another NetworkManager setting overrides the selected backend; configuration was restored.")
        if read_file(SERVICE_CONFIG) != original[SERVICE_CONFIG]:
            run("systemctl", "daemon-reload")
    except Exception:
        for path, text in original.items():
            if text is None:
                path.unlink(missing_ok=True)
            else:
                atomic_write(path, text, modes[path])
        run("systemctl", "daemon-reload", check=False)
        raise
    print(f"[bc250-wifi] Backend {'locked to' if keep_lock else 'set to'} {backend}.")
    if action == "unlock":
        print("[bc250-wifi] Lock removed; the selected backend is retained. Steam can change it again.")
    elif not keep_lock:
        print("[bc250-wifi] Unlocked selection: Steam may override it. Use 'lock' to keep this backend.")
    if before != backend or not service_active(backend):
        other = next(item for item in BACKENDS if item != backend)
        print("[bc250-wifi] Switching Wi-Fi backend; networking will briefly disconnect.", flush=True)
        result = run("bash", str(SWITCH_HELPER), "restart_units", other)
        if result.stdout:
            print(result.stdout, end="")
    else:
        print("[bc250-wifi] Selected backend is already active; no network restart needed.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="action", required=True)
    status = sub.add_parser("status", help="Show effective backend, runtime services, and lock state")
    status.add_argument("--json", action="store_true")
    for action in ("set", "lock"):
        command = sub.add_parser(action, help="Select a backend" if action == "set" else "Select and persistently lock a backend")
        command.add_argument("backend", choices=BACKENDS)
    sub.add_parser("unlock", help="Remove the lock while retaining the selected backend")
    args = parser.parse_args()
    try:
        if args.action == "status":
            show_status(args.json)
        else:
            if os.geteuid() != 0:
                raise WifiError("Administrator access is required.")
            with open("/run/lock/bc250-wifi-backend.lock", "w") as stream:
                fcntl.flock(stream, fcntl.LOCK_EX)
                configure(args.action, getattr(args, "backend", None))
    except (WifiError, OSError, configparser.Error, subprocess.SubprocessError) as error:
        detail = getattr(error, "stderr", None) or str(error)
        parser.exit(1, f"[bc250-wifi] {detail.strip()}\n")


if __name__ == "__main__":
    main()
